-- FASE 0 (revisao 21/09) · criterio de FATURAMENTO/RECEITA = lote 008820 (VENDAS, memoria
-- reference_protheus_codigos_lote). Objetivo: descobrir quais NF de saida geram RECEITA.
-- ago/2026 como referencia (o valor da SF2 com VALFAT>0 foi 13.337.597,23).

-- (a) contas de RECEITA (3110...) movimentadas pelo lote 008820 em ago/26
SELECT TOP 12 RTRIM(CT2_CREDIT) CONTA_CREDITO, COUNT(*) LANCTOS,
       CAST(SUM(CT2_VALOR) AS DECIMAL(18,2)) VALOR
FROM CT2010 WHERE D_E_L_E_T_='' AND CT2_LOTE='008820'
  AND CT2_DATA BETWEEN '20260801' AND '20260831' AND RTRIM(CT2_CREDIT) <> ''
GROUP BY RTRIM(CT2_CREDIT) ORDER BY VALOR DESC;

-- (b) o lote 008820 cobre exatamente as NF com F2_VALFAT>0? comparacao de universos
SELECT 'SF2 ago/26 VALFAT>0' RECORTE, COUNT(*) NF, CAST(SUM(F2_VALFAT) AS DECIMAL(18,2)) VALOR
FROM SF2010 WHERE D_E_L_E_T_='' AND F2_EMISSAO BETWEEN '20260801' AND '20260831' AND F2_VALFAT>0
UNION ALL
SELECT 'NF de saida com lancto no lote 008820', COUNT(DISTINCT F2.F2_DOC+F2.F2_SERIE),
       CAST(SUM(DISTINCTF2.VALFAT) AS DECIMAL(18,2))
FROM (SELECT DISTINCT F2_FILIAL, F2_DOC, F2_SERIE, F2_VALFAT VALFAT FROM SF2010
      WHERE D_E_L_E_T_='' AND F2_EMISSAO BETWEEN '20260801' AND '20260831') DISTINCTF2
JOIN SF2010 F2 ON F2.F2_FILIAL=DISTINCTF2.F2_FILIAL AND F2.F2_DOC=DISTINCTF2.F2_DOC
              AND F2.F2_SERIE=DISTINCTF2.F2_SERIE AND F2.D_E_L_E_T_=''
WHERE EXISTS (SELECT 1 FROM CT2010 CT WHERE CT.D_E_L_E_T_='' AND CT.CT2_LOTE='008820'
              AND CT.CT2_FILIAL=F2.F2_FILIAL AND RTRIM(CT.CT2_DOC)=RTRIM(F2.F2_DOC));
