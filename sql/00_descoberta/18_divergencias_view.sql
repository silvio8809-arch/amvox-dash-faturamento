-- FASE 0 · 3.5 · por que a view mostra 434 NF e a SF2 1888? (valor bate ao centavo)
SELECT 'SF2 ago/26 TODAS' RECORTE, COUNT(*) NF, CAST(SUM(F2_VALFAT) AS DECIMAL(18,2)) VALOR
FROM SF2010 WHERE D_E_L_E_T_='' AND F2_EMISSAO BETWEEN '20260801' AND '20260831'
UNION ALL
SELECT 'SF2 ago/26 com VALFAT>0', COUNT(*), CAST(SUM(F2_VALFAT) AS DECIMAL(18,2))
FROM SF2010 WHERE D_E_L_E_T_='' AND F2_EMISSAO BETWEEN '20260801' AND '20260831' AND F2_VALFAT > 0
UNION ALL
SELECT 'SF2 ago/26 com VALFAT=0', COUNT(*), 0
FROM SF2010 WHERE D_E_L_E_T_='' AND F2_EMISSAO BETWEEN '20260801' AND '20260831' AND F2_VALFAT = 0;

-- o que sao as notas de valor zero? amostra por TES/CFOP do item
SELECT TOP 10 D2.D2_CF CFOP, COUNT(DISTINCT F2.F2_DOC) NF
FROM SF2010 F2 JOIN SD2010 D2 ON D2.D2_FILIAL=F2.F2_FILIAL AND D2.D2_DOC=F2.F2_DOC
            AND D2.D2_SERIE=F2.F2_SERIE AND D2.D_E_L_E_T_=''
WHERE F2.D_E_L_E_T_='' AND F2.F2_EMISSAO BETWEEN '20260801' AND '20260831' AND F2.F2_VALFAT = 0
GROUP BY D2.D2_CF ORDER BY NF DESC;

-- "DT SAI" da view corresponde a E1_DTSAIDA? conferir numa NF
SELECT TOP 5 V.NF, V.[DT SAI] VIEW_DT_SAI, F2.F2_DTENTR SF2_DTENTR, E1.E1_DTSAIDA SE1_DTSAIDA
FROM (SELECT DISTINCT NF, [DT SAI], [DT NF] FROM VW_AZ_FATURAMENTO_ANALITICO_NOVO
      WHERE [DT NF] BETWEEN '20260801' AND '20260831' AND ORIGEM='FAT' AND [DT SAI] <> '') V
JOIN SF2010 F2 ON F2.F2_DOC = RIGHT(V.NF,9) AND F2.D_E_L_E_T_=''
LEFT JOIN SE1010 E1 ON E1.E1_NUM = F2.F2_DOC AND E1.E1_PREFIXO = F2.F2_SERIE AND E1.D_E_L_E_T_=''
ORDER BY V.NF;
