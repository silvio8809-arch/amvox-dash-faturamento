-- FASE 0 (revisao 21/09) · como identificar "operacao de faturamento (receita)" no nivel da NF
-- (a) amostra da chave contabil do lote 008820 (CT2_DOC/CT2_KEY nao sao o numero da NF)
SELECT TOP 5 CT2_FILIAL, CT2_DATA, CT2_LOTE, CT2_DOC, LEFT(CT2_KEY,40) CT2_KEY,
       RTRIM(CT2_DEBITO) DEB, RTRIM(CT2_CREDIT) CRED, CAST(CT2_VALOR AS DECIMAL(18,2)) VALOR
FROM CT2010 WHERE D_E_L_E_T_='' AND CT2_LOTE='008820' AND CT2_DATA BETWEEN '20260801' AND '20260831'
  AND RTRIM(CT2_CREDIT)='3110101003';

-- (b) CFOP x valor faturado: o corte VALFAT>0 separa RECEITA de REMESSA? (ago/26)
SELECT CASE WHEN F2.F2_VALFAT > 0 THEN 'COM faturamento' ELSE 'SEM faturamento (VALFAT=0)' END RECORTE,
       D2.D2_CF CFOP, COUNT(DISTINCT F2.F2_DOC+F2.F2_SERIE) NF
FROM SF2010 F2 JOIN SD2010 D2 ON D2.D2_FILIAL=F2.F2_FILIAL AND D2.D2_DOC=F2.F2_DOC
            AND D2.D2_SERIE=F2.F2_SERIE AND D2.D_E_L_E_T_=''
WHERE F2.D_E_L_E_T_='' AND F2.F2_EMISSAO BETWEEN '20260801' AND '20260831'
GROUP BY CASE WHEN F2.F2_VALFAT > 0 THEN 'COM faturamento' ELSE 'SEM faturamento (VALFAT=0)' END, D2.D2_CF
HAVING COUNT(DISTINCT F2.F2_DOC+F2.F2_SERIE) >= 3
ORDER BY RECORTE, NF DESC;
