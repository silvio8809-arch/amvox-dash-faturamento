-- FASE 0 · 3.5 · a view serve de base para EMITIDAS? cruzar com a SF2 (ago/2026)
SELECT 'SF2010 (direto)' FONTE, COUNT(*) NF, CAST(SUM(F2_VALFAT) AS DECIMAL(18,2)) VALOR
FROM SF2010 WHERE D_E_L_E_T_='' AND F2_EMISSAO BETWEEN '20260801' AND '20260831'
UNION ALL
SELECT 'VIEW ORIGEM=FAT', COUNT(DISTINCT NF), CAST(SUM(FATURAMENTO) AS DECIMAL(18,2))
FROM VW_AZ_FATURAMENTO_ANALITICO_NOVO
WHERE [DT NF] BETWEEN '20260801' AND '20260831' AND ORIGEM='FAT';

-- a coluna "DT SAI" da view corresponde a data de entrega? comparar com E1_DTSAIDA/F2_DTENTR
SELECT TOP 8 NF, [DT NF], [DT SAI], [1 RECEBIMENTO], ORIGEM
FROM VW_AZ_FATURAMENTO_ANALITICO_NOVO
WHERE [DT NF] BETWEEN '20260801' AND '20260831' AND ORIGEM='FAT' ORDER BY NF;

-- devolucoes na view x SF1 tipo D (ago/2026)
SELECT 'SF1 tipo D' FONTE, COUNT(*) NF, CAST(SUM(F1_VALBRUT) AS DECIMAL(18,2)) VALOR
FROM SF1010 WHERE D_E_L_E_T_='' AND F1_TIPO='D' AND F1_EMISSAO BETWEEN '20260801' AND '20260831'
UNION ALL
SELECT 'VIEW ORIGEM=DEV', COUNT(DISTINCT NF), CAST(SUM(DEVOLUCAO) AS DECIMAL(18,2))
FROM VW_AZ_FATURAMENTO_ANALITICO_NOVO
WHERE [DT NF] BETWEEN '20260801' AND '20260831' AND ORIGEM='DEV';
